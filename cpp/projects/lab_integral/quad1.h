// ================== МЕТОД ЛЕВЫХ ПРЯМОУГОЛЬНИКОВ ==================
double left_rect(double (*f)(double), double inf, double sup, double eps, size_t& n) {
    // double (*f)(double) — указатель на функцию f(x)
    // eps — требуемая точность
    // n — сюда вернётся итоговое число разбиений N

    size_t i;
    // переменная-счётчик цикла

    size_t N = 2;
    // начальное количество разбиений (очень грубое приближение)

    size_t Nmax = 16384;
    // максимальное число разбиений (чтобы не зациклиться)

    double J;
    // значение интеграла на предыдущей итерации

    double J2;
    // значение интеграла на текущей итерации

    double h = (sup - inf) / N;
    // шаг разбиения: длина каждого маленького отрезка



    J2 = (f(inf) + f(inf + 0.5 * h)) * h;
    // первый грубый расчёт интеграла
    // берём значение функции в левой точке и примерно в середине
    // умножаем сумму на шаг



    do {
        // основной цикл уточнения

        J = J2;
        // сохраняем предыдущее значение интеграла

        N += N;
        // увеличиваем количество разбиений в 2 раза (N = 2N)

        h = (sup - inf) / N;
        // пересчитываем шаг (он стал меньше)



        for (J2 = 0, i = 0; i < N; ++i)
            // обнуляем сумму J2 и запускаем цикл по всем отрезкам

            J2 += f(inf + h * i);
        // добавляем значение функции в ЛЕВОЙ точке каждого отрезка
        // x_i = inf + i*h

        J2 *= h;
        // умножаем сумму на шаг → получаем приближённый интеграл



    } while (
        fabs(J - J2) > eps * fabs(J2)
        // если разница между итерациями больше заданной точности — продолжаем

        && N < Nmax
        // и при этом не превышено максимальное число разбиений
        );

    n = N;
    // записываем итоговое число разбиений в переменную n

    return J2;
    // возвращаем вычисленный интеграл
}

// ================== МЕТОД СРЕДНИХ ПРЯМОУГОЛЬНИКОВ ==================
double mid_rect(double (*f)(double), double inf, double sup, double eps, size_t& n) {

    size_t i;
    // счётчик цикла

    size_t N = 2, Nmax = 16384;
    // начальное число разбиений и ограничение

    double J, J2 = 0;
    // J — старое значение
    // J2 — текущее значение (сразу инициализируем 0)

    double h = (sup - inf) / N;
    // шаг разбиения



    do {
        J = J2;
        // сохраняем старое значение

        N += N;
        // увеличиваем число отрезков

        h = (sup - inf) / N;
        // уменьшаем шаг



        for (J2 = 0, i = 0; i < N; ++i)
            // обнуляем сумму и идём по всем отрезкам

            J2 += f(inf + h * (i + 0.5));
        // берём значение функции в СЕРЕДИНЕ отрезка
        // это главное отличие метода

        J2 *= h;
        // умножаем сумму на шаг



    } while (fabs(J - J2) > eps * fabs(J2) && N < Nmax);

    n = N;
    // возвращаем число разбиений

    return J2;
    // возвращаем интеграл
}

// ================== МЕТОД ТРАПЕЦИЙ ==================
double trapezoid(double (*f)(double), double inf, double sup, double eps, size_t& n) {

    size_t i;
    // счётчик

    size_t N = 2, Nmax = 16384;
    // число разбиений

    double J, J2 = 0;
    // J — старое значение, J2 — новое

    double h = (sup - inf) / N;
    // шаг



    do {
        J = J2;
        // сохраняем предыдущее значение

        N += N;
        // увеличиваем число разбиений

        h = (sup - inf) / N;
        // пересчитываем шаг



        J2 = (f(inf) + f(sup)) / 2.0;
        // учитываем крайние точки
        // они входят с коэффициентом 1/2



        for (i = 1; i < N; ++i)
            // цикл по внутренним точкам

            J2 += f(inf + i * h);
        // добавляем значения функции в этих точках



        J2 *= h;
        // умножаем на шаг



    } while (fabs(J - J2) > eps * fabs(J2) && N < Nmax);

    n = N;

    return J2;
}

// ================== МЕТОД СИМПСОНА ==================
double simpson(double (*f)(double), double inf, double sup, double eps, size_t& n) {

    size_t i;
    // счётчик

    size_t N = 2, Nmax = 16384;
    // N должно быть чётным (мы удваиваем — это гарантируется)

    double J, J2 = 0;
    // значения интеграла

    double h;
    // шаг (объявляем отдельно)



    do {
        J = J2;
        // сохраняем старое значение

        N += N;
        // увеличиваем N

        h = (sup - inf) / N;
        // пересчитываем шаг



        double sum_odd = 0;
        // сумма значений в нечётных точках (коэффициент 4)

        double sum_even = 0;
        // сумма значений в чётных точках (коэффициент 2)



        for (i = 1; i < N; i += 2)
            // идём по нечётным индексам

            sum_odd += f(inf + i * h);
        // добавляем значения функции



        for (i = 2; i < N; i += 2)
            // идём по чётным индексам

            sum_even += f(inf + i * h);
        // добавляем значения



        J2 = (f(inf) + f(sup) + 4 * sum_odd + 2 * sum_even) * h / 3.0;
        // формула Симпсона:
        // крайние точки + 4*нечётные + 2*чётные
        // умножаем на h/3



    } while (fabs(J - J2) > eps * fabs(J2) && N < Nmax);

    n = N;

    return J2;
}