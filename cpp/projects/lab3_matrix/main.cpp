    // Создаём две матрицы размером 2x2 
    Matrix A(2, 2);
    Matrix B(2, 2);

    // Вводим элементы
    cout << "Ввод матрицы A (2x2):\n";
    A.input();
    cout << "Ввод матрицы B (2x2):\n";
