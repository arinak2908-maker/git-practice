#include <iostream>   // cin, cout, endl
#include <cstdlib>    // для exit (аварийное завершение программы при ошибке)

using namespace std;  // чтобы не писать std:: перед cin, cout

// ===============================================================
// КЛАСС MATRIX
// ===============================================================
// Класс представляет матрицу вещественных чисел (float).
// Данные хранятся в одномерном динамическом массиве.
// Доступ к элементам осуществляется через оператор () с индексами,
// начинающимися с 1 (как в математике).
// Реализованы основные матричные операции: сложение, вычитание,
// умножение матриц, умножение на число, унарный минус,
// перестановка строк и столбцов, ввод и вывод.
// ===============================================================
class Matrix {
private:
    int rows;    // количество строк (нумерация с 1)
    int cols;    // количество столбцов (нумерация с 1)
    float* a;    // указатель на динамический массив элементов матрицы

public:
    // ------------------------------------------------------------------
    // КОНСТРУКТОР ПО УМОЛЧАНИЮ
    // Создаёт "пустую" матрицу, в которой нет элементов.
    // Зачем нужен? Чтобы можно было объявлять массив объектов Matrix,
    // а потом присваивать им реальные матрицы.
    // ------------------------------------------------------------------
    Matrix() {
        rows = 0;
        cols = 0;
        a = nullptr;   // nullptr означает, что память не выделена
    }

    // ------------------------------------------------------------------
    // КОНСТРУКТОР С ПАРАМЕТРАМИ (РАЗМЕРЫ)
    // Создаёт матрицу размера r x c, заполняет её нулями.
    // Параметры: r – количество строк, c – количество столбцов.
    // ------------------------------------------------------------------
    Matrix(int r, int c) {
        // Проверка: размеры должны быть положительными
        if (r <= 0 || c <= 0) {
            cout << "Ошибка: размеры матрицы должны быть больше 0\n";
            exit(1);   // немедленно завершаем программу с кодом ошибки 1
        }
        rows = r;
        cols = c;
        // Выделяем память под rows * cols элементов типа float
        // new float[N] – выделяет массив из N чисел float, возвращает указатель
        a = new float[rows * cols];
        // Заполняем массив нулями
        for (int i = 0; i < rows * cols; ++i) {
            a[i] = 0.0f;
        }
    }

    // ------------------------------------------------------------------
    // КОНСТРУКТОР КОПИРОВАНИЯ
    // Создаёт новый объект как копию существующего.
    // Вызывается, когда пишут: Matrix B = A; или передают матрицу в функцию по значению.
    // Без него компилятор сгенерировал бы поверхностное копирование (скопировал бы
    // только указатель a, и два объекта стали бы ссылаться на одну память – это ошибка).
    // ------------------------------------------------------------------
    Matrix(const Matrix& m) {
        rows = m.rows;
        cols = m.cols;
        // Выделяем НОВУЮ память под копию данных
        a = new float[rows * cols];
        // Копируем все элементы из исходной матрицы m в новую
        for (int i = 0; i < rows * cols; ++i) {
            a[i] = m.a[i];
        }
    }

    // ------------------------------------------------------------------
    // ДЕСТРУКТОР
    // Вызывается автоматически, когда объект уничтожается (выходит из области видимости,
    // удаляется через delete). Освобождает память, выделенную под массив a.
    // Зачем? Чтобы не было утечки памяти.
    // ------------------------------------------------------------------
    ~Matrix() {
        delete[] a;   // delete[] – освобождает память, выделенную new[]
    }

    // ------------------------------------------------------------------
    // ОПЕРАТОР ПРИСВАИВАНИЯ (operator=)
    // Позволяет писать: A = B; (копирование данных из B в A).
    // Возвращает ссылку на текущий объект (*this) – это позволяет писать цепочки A=B=C.
    // Нужен, потому что компилятор сгенерировал бы поверхностное копирование.
    // ------------------------------------------------------------------
    Matrix& operator=(const Matrix& m) {
        // Проверка на самоприсваивание: если A = A, ничего не делаем.
        // this – указатель на текущий объект, &m – адрес переданной матрицы.
        // Если адреса совпадают, значит это один и тот же объект.
        if (this == &m) {
            return *this;   // возвращаем текущий объект
        }
        // Освобождаем старую память, чтобы не было утечки
        delete[] a;
        // Копируем размеры из m
        rows = m.rows;
        cols = m.cols;
        // Выделяем новую память
        a = new float[rows * cols];
        // Копируем элементы
        for (int i = 0; i < rows * cols; ++i) {
            a[i] = m.a[i];
        }
        // *this – разыменованный указатель, т.е. сам объект. Возвращаем его по ссылке.
        return *this;
    }

    // ------------------------------------------------------------------
    // ОПЕРАТОР ДОСТУПА К ЭЛЕМЕНТУ (круглые скобки)
    // Позволяет писать: A(i, j) для чтения или записи элемента.
    // Индексы i, j начинаются с 1 (как в математике).
    // Возвращает ссылку, чтобы можно было изменять элемент: A(i,j) = 5;
    // ------------------------------------------------------------------
    float& operator()(int i, int j) {
        // Проверка границ: i от 1 до rows, j от 1 до cols
        if (i < 1 || i > rows || j < 1 || j > cols) {
            cout << "Ошибка: индекс вне границ матрицы\n";
            exit(1);
        }
        // Элементы в одномерном массиве хранятся построчно:
        // строка 1: элементы с индексами 0..cols-1,
        // строка 2: элементы с индексами cols..2*cols-1 и т.д.
        // Формула: (i-1)*cols + (j-1)
        return a[(i - 1) * cols + (j - 1)];
    }

    // ------------------------------------------------------------------
    // CONST-ВЕРСИЯ ОПЕРАТОРА ()
    // Нужна для работы с константными объектами (например, при передаче по константной ссылке).
    // Возвращает константную ссылку – такой элемент нельзя изменить.
    // ------------------------------------------------------------------
    const float& operator()(int i, int j) const {
        if (i < 1 || i > rows || j < 1 || j > cols) {
            cout << "Ошибка: индекс вне границ матрицы\n";
            exit(1);
        }
        return a[(i - 1) * cols + (j - 1)];
    }

    // ------------------------------------------------------------------
    // СЛОЖЕНИЕ МАТРИЦ (A + B)
    // Требует одинаковых размеров.
    // ------------------------------------------------------------------
    Matrix operator+(const Matrix& m) const {
        // Проверка: количество строк и столбцов должно совпадать
        if (rows != m.rows || cols != m.cols) {
            cout << "Ошибка: при сложении размеры матриц не совпадают\n";
            exit(1);
        }
        Matrix res(rows, cols);   // создаём матрицу для результата
        for (int i = 0; i < rows * cols; ++i) {
            res.a[i] = a[i] + m.a[i];   // поэлементное сложение
        }
        return res;   // возвращаем результат (вызывается конструктор копирования)
    }

    // ------------------------------------------------------------------
    // СЛОЖЕНИЕ МАТРИЦЫ С ЧИСЛОМ (A + x)
    // Прибавляет число x к каждому элементу матрицы.
    // ------------------------------------------------------------------
    Matrix operator+(float x) const {
        Matrix res(rows, cols);
        for (int i = 0; i < rows * cols; ++i) {
            res.a[i] = a[i] + x;
        }
        return res;
    }

    // ------------------------------------------------------------------
    // ВЫЧИТАНИЕ МАТРИЦ (A - B)
    // ------------------------------------------------------------------
    Matrix operator-(const Matrix& m) const {
        if (rows != m.rows || cols != m.cols) {
            cout << "Ошибка: при вычитании размеры матриц не совпадают\n";
            exit(1);
        }
        Matrix res(rows, cols);
        for (int i = 0; i < rows * cols; ++i) {
            res.a[i] = a[i] - m.a[i];
        }
        return res;
    }

    // ------------------------------------------------------------------
    // УНАРНЫЙ МИНУС (-A)
    // Меняет знак всех элементов матрицы.
    // ------------------------------------------------------------------
    Matrix operator-() const {
        Matrix res(rows, cols);
        for (int i = 0; i < rows * cols; ++i) {
            res.a[i] = -a[i];
        }
        return res;
    }

    // ------------------------------------------------------------------
    // УМНОЖЕНИЕ МАТРИЦ (A * B)
    // Классическое матричное умножение: число столбцов A должно равняться числу строк B.
    // Размер результата: (rows A) x (cols B).
    // Формула: C(i,j) = сумма по k от 1 до cols(A) от A(i,k) * B(k,j).
    // ------------------------------------------------------------------
    Matrix operator*(const Matrix& m) const {
        // Проверка возможности умножения
        if (cols != m.rows) {
            cout << "Ошибка: количество столбцов первой матрицы не равно количеству строк второй\n";
            exit(1);
        }
        Matrix res(rows, m.cols);   // результирующая матрица размера rows x m.cols
        // Тройной цикл перемножения
        for (int i = 1; i <= rows; ++i) {           // по строкам результата
            for (int j = 1; j <= m.cols; ++j) {     // по столбцам результата
                float sum = 0.0f;
                for (int k = 1; k <= cols; ++k) {   // по общему измерению
                    // (*this)(i,k) – элемент A[i][k]
                    // m(k,j)      – элемент B[k][j]
                    sum += (*this)(i, k) * m(k, j);
                }
                res(i, j) = sum;   // записываем в результат
            }
        }
        return res;
    }

    // ------------------------------------------------------------------
    // УМНОЖЕНИЕ МАТРИЦЫ НА ЧИСЛО (A * x)
    // ------------------------------------------------------------------
    Matrix operator*(float x) const {
        Matrix res(rows, cols);
        for (int i = 0; i < rows * cols; ++i) {
            res.a[i] = a[i] * x;
        }
        return res;
    }

    // ------------------------------------------------------------------
    // ПЕРЕСТАНОВКА СТРОК
    // Меняет местами строки r1 и r2 (нумерация с 1).
    // ------------------------------------------------------------------
    void swap_rows(int r1, int r2) {
        if (r1 < 1 || r1 > rows || r2 < 1 || r2 > rows) {
            cout << "Ошибка: неверный номер строки при перестановке\n";
            exit(1);
        }
        // Проходим по всем столбцам
        for (int j = 1; j <= cols; ++j) {
            float temp = (*this)(r1, j);   // сохраняем элемент из первой строки
            (*this)(r1, j) = (*this)(r2, j); // копируем из второй в первую
            (*this)(r2, j) = temp;           // копируем сохранённое во вторую
        }
    }

    // ------------------------------------------------------------------
    // ПЕРЕСТАНОВКА СТОЛБЦОВ
    // Меняет местами столбцы c1 и c2 (нумерация с 1).
    // ------------------------------------------------------------------
    void swap_columns(int c1, int c2) {
        if (c1 < 1 || c1 > cols || c2 < 1 || c2 > cols) {
            cout << "Ошибка: неверный номер столбца при перестановке\n";
            exit(1);
        }
        for (int i = 1; i <= rows; ++i) {
            float temp = (*this)(i, c1);
            (*this)(i, c1) = (*this)(i, c2);
            (*this)(i, c2) = temp;
        }
    }

    // ------------------------------------------------------------------
    // ВВОД МАТРИЦЫ С КЛАВИАТУРЫ
    // Запрашивает ввод всех элементов построчно.
    // ------------------------------------------------------------------
    void input() {
        cout << "Введите элементы матрицы " << rows << "x" << cols << ":\n";
        for (int i = 1; i <= rows; ++i) {
            for (int j = 1; j <= cols; ++j) {
                cin >> (*this)(i, j);   // оператор () возвращает ссылку, в которую записываем значение
            }
        }
    }

    // ------------------------------------------------------------------
    // ВЫВОД МАТРИЦЫ НА ЭКРАН
    // ------------------------------------------------------------------
    void print() const {
        for (int i = 1; i <= rows; ++i) {
            for (int j = 1; j <= cols; ++j) {
                cout << (*this)(i, j) << " ";
            }
            cout << endl;
        }
    }
};

