// comp.h — Заголовочный файл класса comp для работы с комплексными числами
// ============================================================================
// Зачем нужен .h файл?
// • В заголовочных файлах объявляем интерфейс класса: какие поля и методы есть
// • Не пишем реализацию методов (кроме очень простых) — это делаем в .cpp
// • #pragma once предотвращает повторное включение файла при компиляции
// ============================================================================

#pragma once

// Подключаем необходимые стандартные библиотеки
#include <iostream>   // Для std::ostream (вывод в консоль через operator<<)
#include <cmath>      // Для математических функций: sqrt, atan2, M_PI
#include<corecrt_math_defines.h>
// СИНТАКСИС: специфичный для Visual Studio заголовок
// ЗАЧЕМ: определение математических констант (закомментирован, т.к. math.h их уже определяет)

// ============================================================================
// Класс comp — представление комплексного числа z = x + i*y
// ============================================================================
// Что такое комплексное число?
// • Это число вида z = x + i·y, где:
//   - x — вещественная часть (Re z)
//   - y — мнимая часть (Im z)
//   - i — мнимая единица, i² = -1
// ============================================================================

class comp {
private:
    // === ЗАКРЫТАЯ СЕКЦИЯ (private) ===
    // Поля доступны только внутри класса — это инкапсуляция
    float x;  // Вещественная часть комплексного числа
    float y;  // Мнимая часть комплексного числа

public:
    // === ОТКРЫТАЯ СЕКЦИЯ (public) — интерфейс класса ===

    // ------------------------------------------------------------------------
    // Конструктор с параметрами по умолчанию
    // ------------------------------------------------------------------------
    // Синтаксис: comp(float r = 0.0f, float i = 0.0f)
    // • Параметры по умолчанию позволяют вызывать конструктор 3 способами:
    //   1) comp z;           → z(0.0, 0.0) — оба нуля
    //   2) comp z(5.0);      → z(5.0, 0.0) — только вещественная часть
    //   3) comp z(3.0, 4.0); → z(3.0, 4.0) — обе части заданы
    // • :x(r), y(i) — список инициализации (эффективнее присваивания в теле)
    // • Явный/неявный конструктор: 
    //   Если убрать explicit, компилятор сможет неявно преобразовать float → comp
    //   Например: comp z = 5.0; // неявный вызов comp(5.0)
    //   Мы НЕ используем explicit, чтобы разрешить такие удобные преобразования
    // ------------------------------------------------------------------------
    comp(float r = 0.0f, float i = 0.0f);

    // ------------------------------------------------------------------------
    // Геттеры — методы для получения значений полей
    // ------------------------------------------------------------------------
    // Почему const после имени метода?
    // • Это обещание, что метод не изменит объект
    // • Позволяет вызывать метод у константных объектов: const comp z; z.Re();
    // ------------------------------------------------------------------------
    float Re() const;  // Возвращает вещественную часть (x)
    float Im() const;  // Возвращает мнимую часть (y)

    // ------------------------------------------------------------------------
    // Основные методы работы с комплексными числами
    // ------------------------------------------------------------------------
    float mod() const;     // Модуль: |z| = √(x² + y²)
    float arg() const;     // Аргумент: угол φ ∈ [0; 2π), где z = |z|·e^(iφ)
    comp cnj() const;      // Комплексно-сопряжённое: z* = x - i·y

    // ------------------------------------------------------------------------
    // Унарные операторы (работают с одним операндом — этим объектом)
    // ------------------------------------------------------------------------
    comp operator+() const;  // Унарный плюс: +z (возвращает копию)
    comp operator-() const;  // Унарный минус: -z = -x - i·y

    // ------------------------------------------------------------------------
    // Бинарные арифметические операторы (комплекс + комплекс)
    // ------------------------------------------------------------------------
    // Почему const после параметров и метода?
    // • const fcomplex& — не изменяем переданный объект (эффективно + безопасно)
    // • const после ) — метод не меняет текущий объект (*this)
    // ------------------------------------------------------------------------
    comp operator+(const comp&) const;  // Сложение: z1 + z2
    comp operator-(const comp&) const;  // Вычитание: z1 - z2
    comp operator*(const comp&) const;  // Умножение: (x1+iy1)(x2+iy2)
    comp operator/(const comp&) const;  // Деление: z1/z2 = z1·z2*/|z2|²

    // ------------------------------------------------------------------------
    // Дружественные функции (friend) — имеют доступ к private-полям
    // ------------------------------------------------------------------------
    // Зачем friend?
    // • Позволяют писать операторы в симметричной форме: 5.0 + z и z + 5.0
    // • Без friend пришлось бы писать только z + 5.0 (через метод класса)
    // • Объявляются внутри класса, но реализуются снаружи как обычные функции
    // ------------------------------------------------------------------------
    friend comp operator+(float, const comp&);  // float + comp
    friend comp operator-(float, const comp&);  // float - comp
    friend comp operator*(float, const comp&);  // float * comp
    friend comp operator/(float, const comp&);  // float / comp

    // ------------------------------------------------------------------------
    // Оператор вывода в поток (для cout << z)
    // ------------------------------------------------------------------------
    // Почему именно friend?
    // • operator<< должен быть слева от <<, а левый операнд — std::ostream
    // • Мы не можем изменить класс std::ostream, поэтому делаем функцию-друга
    // Формат вывода: (вещественная,мнимая) → например: (3,2)
    // ------------------------------------------------------------------------
    friend std::ostream& operator<<(std::ostream&, const comp&);
};

