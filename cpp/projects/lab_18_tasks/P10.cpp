#pragma once                      // Защита от повторного включения файла
#include <iostream>               // Подключаем библиотеку для ввода/вывода
#include <cstdlib>                // Подключаем библиотеку для функций rand() и srand()
#include <ctime>                  // Подключаем библиотеку для функции time()

using std::cin;                   // Используем cin из пространства std
using std::cout;                  // Используем cout из пространства std
using std::endl;                  // Используем endl из пространства std

int main() {
    setlocale(LC_ALL, ".1251");   // Устанавливаем русскую кодировку для вывода текста
    
    // "Настраиваем генератор случайных чисел на текущее время"
    // Это нужно, чтобы при каждом запуске программы получались разные случайные числа
    srand(static_cast<unsigned int>(time(0)));
    
    // Выводим условие задачи на экран, чтобы пользователь понимал, что делает программа
    cout << "Задание: Программа генерирует беззнаковое целое число m в диапазоне" << endl;
    cout << "30 <= m <= 300 и положительное целое n(3 <= n <= 12 ); далее создаётся" << endl;
    cout << "динамический массив A из N = n*m случайных целых чисел из диапазона от" << endl;
    cout << "1 до m.Затем, считая известным только число N(т.е.т и n считать"<<endl;
    cout << "неизвестными), определить и вывести на экран построчно взятые в кавычки"<<endl;
    cout << "значения и через тире количество вхождений этого значения а массиве A."<<endl;
    cout << "Например, “15” - 4 означает, что значение 15 встретилось в массиве 4 раза.\n"<<endl;

    // 1. "Генерируем два случайных числа m и n в заданных диапазонах"
    unsigned int m = 30 + rand() % 271;  // m случайное число от 30 до 300
    unsigned int n = 3 + rand() % 10;    // n случайное число от 3 до 12
    unsigned int N = n * m;              // N = n * m (общее количество чисел в массиве)

    // 2. "Создаем динамический массив A размером N"
    unsigned int* A = new unsigned int[N];

    // 3. "Заполняем массив A случайными числами от 1 до m"
    for (unsigned int i = 0; i < N; ++i) {
        A[i] = 1 + rand() % m; // Случайное число от 1 до m
    }

    // 4. "Сортируем массив A по возрастанию, чтобы одинаковые числа стояли рядом"
    // Используем метод пузырьковой сортировки
    for (unsigned int i = 0; i < N - 1; ++i) {
        for (unsigned int j = 0; j < N - i - 1; ++j) {
            if (A[j] > A[j + 1]) {
                // Если текущий элемент больше следующего, меняем их местами
                unsigned int temp = A[j];
                A[j] = A[j + 1];
                A[j + 1] = temp;
            }
        }
    }

    // 5. "Подсчитываем, сколько раз встречается каждое число в отсортированном массиве"
    unsigned int current_value = A[0]; // Запоминаем первое число в массиве
    unsigned int count = 1;            // Счетчик для этого числа (уже один раз встретилось)

    // Проходим по массиву, начиная со второго элемента
    for (unsigned int i = 1; i < N; ++i) {
        if (A[i] == current_value) {
            ++count; // Если число такое же как предыдущее, увеличиваем счетчик
        }
        else {
            // Если встретили новое число, выводим предыдущее число и сколько раз оно встретилось
            cout << "\"" << current_value << "\" - " << count << endl;
            current_value = A[i]; // Запоминаем новое число
            count = 1;            // Сбрасываем счетчик для нового числа
        }
    }

    // 6. "Выводим последнее число и количество его вхождений"
    // (после цикла последнее число еще не выведено)
    cout << "\"" << current_value << "\" - " << count << endl;

    // 7. "Освобождаем память, которую выделили для массива A"
    delete[] A;

    cout << endl;
    system("pause"); // Ожидаем нажатия клавиши перед закрытием окна
}