#pragma once                      // Защита от повторного включения файла
#include <iostream>               // Подключаем библиотеку для ввода/вывода
#include <cstdlib>                // Подключаем библиотеку для функций rand() и srand()
#include <ctime>                  // Подключаем библиотеку для функции time()

using std::cin;                   // Используем cin из пространства std
using std::cout;                  // Используем cout из пространства std
using std::endl;                  // Используем endl из пространства std

int main() {
    setlocale(LC_ALL, ".1251");   // Устанавливаем русскую кодировку для вывода текста

    // "Настраиваем генератор случайных чисел на текущее время"
    // Это нужно, чтобы при каждом запуске программы получались разные случайные числа
    srand(static_cast<unsigned int>(time(0)));

    // Выводим условие задачи на экран, чтобы пользователь понимал, что делает программа
    cout << "Задание: Статический массив хранит целые числа от 1 до N – номера студентов" << endl;
    cout << "по списку группы.Для выполнения работ в лаборатории требуется не менее" << endl;
    cout << "двух и не более трёх человек на одну установку, т.е.студенты должны" << endl;
    cout << "разбиться на пары, а если количество студентов в группе нечётное – то на пары" << endl;
    cout << "и одну тройку.Программа должна случайным образом(не по списку группы)" << endl;
    cout << "разбить исходный массив номеров на пары(или на пары и одну тройку)." << endl;
    cout << "Каждая пара или тройка должна быть выведена на экран с новой строки," << endl;
    cout << "элементы пары(тройки) отделяются запятыми.\n" << endl;

    const int N = 25;  // Фиксируем количество студентов (25 человек)
    int students[N];   // Создаем массив для хранения номеров 25 студентов

    // "Заполняем массив номерами от 1 до 25 по порядку"
    for (int i = 0; i < N; ++i) {
        students[i] = i + 1; // students[0] = 1, students[1] = 2, ..., students[24] = 25
    }

    // "Перемешиваем массив как колоду карт - делаем случайный порядок номеров"
    // Алгоритм: идем с конца массива к началу, меняя текущий элемент со случайным
    for (int i = N - 1; i > 0; --i) {
        int j = rand() % (i + 1); // Выбираем случайный индекс от 0 до i

        // Меняем местами два элемента массива
        int temp = students[i];
        students[i] = students[j];
        students[j] = temp;
    }

    // Выводим заголовок результата
    cout << "Случайное разбиение 25 студентов на пары и тройку:" << endl;

    int index = 0; // Начинаем с первого элемента массива

    // "Если количество студентов нечетное, формируем одну тройку"
    if (N % 2 == 1) {
        // Берем первые три элемента перемешанного массива - это будет тройка
        cout << "Тройка: "
            << students[0] << ", "
            << students[1] << ", "
            << students[2] << endl;
        index = 3; // После тройки продолжаем с 4-го элемента (индекс 3)
    }

    // "Оставшихся студентов разбиваем на пары"
    // Берем элементы попарно: (0,1), (2,3), (4,5) и т.д.
    for (; index < N; index += 2) {
        cout << "Пара: "
            << students[index] << ", "
            << students[index + 1] << endl;
    }

    cout << endl;
    system("pause"); // Ожидаем нажатия клавиши перед закрытием окна
}