// ______________________________________________________________
// РЕАЛИЗАЦИЯ ФУНКЦИИ SIN(x)
// _____________________________________________________________
double SIN(double x) {
    // 1. "Приводим аргумент к диапазону [-pi, pi]"
    // Это нужно потому, что ряд Тейлора плохо сходится для больших x
    double two_pi = 2.0 * PI;  // 2pi = примерно 6.283185307179586
    x = fmod(x, two_pi);         // Находим остаток от деления на 2pi

    // 2. "Если x больше pi, вычитаем 2pi; если меньше -pi, прибавляем 2pi"
    if (x > PI) {
        x -= two_pi;             // Пример: x = 4 -> 4 - 6.283 = -2.283
    }
    else if (x < -PI) {
        x += two_pi;             // Пример: x = -4 -> -4 + 6.283 = 2.283
    }

    // 3. "Задаем точность вычислений"
    const double epsilon = 1e-12; // Очень маленькое число для точности

    // 4. "Инициализируем переменные для вычисления ряда"
    double term = x;             // Первое слагаемое (при k=0): x1/1! = x
    double sum = term;           // Текущая сумма ряда
    double x_squared = x * x;    // x2, будем использовать много раз
    int k = 0;                   // Номер текущего слагаемого

    // 5. "Вычисляем сумму ряда Тейлора"
    // Пока очередное слагаемое больше заданной точности
    while (fabs(term) > epsilon) {
        k++;  // Переходим к следующему слагаемому

        // 6. "Вычисляем следующее слагаемое через предыдущее"
        // Формула: term_{k} = -term_{k-1} * x2 / ((2k)*(2k+1))
        term = -term * x_squared / ((2.0 * k) * (2.0 * k + 1.0));

        // 7. "Добавляем слагаемое к общей сумме"
        sum += term;
    }

    // 8. "Возвращаем результат"
    return sum;
}