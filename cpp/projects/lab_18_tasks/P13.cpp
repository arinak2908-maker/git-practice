#pragma once                      // Защита от повторного включения файла
#include <iostream>               // Подключаем библиотеку для ввода/вывода

using std::cin;                   // Используем cin из пространства std
using std::cout;                  // Используем cout из пространства std
using std::endl;                  // Используем endl из пространства std

int main() {
    setlocale(LC_ALL, ".1251");   // Устанавливаем русскую кодировку для вывода текста

    cout << "Задание: С клавиатуры вводится целое беззнаковое число от 10 до 1000000000.";
    cout << "Вывести с новой строки цифры этого числа в обратном порядке.";
    cout << "Например: вход: 12345  выход: 54321\n" << endl;

    // 1. Ввод числа
    unsigned int number;

    cout << "Введите целое беззнаковое число от 10 до 1000000000: ";
    cin >> number;

    // 2. Проверка диапазона
    // "Если число меньше 10 ИЛИ число больше 1000000000"
    if (number < 10 || number > 1000000000) {
        cout << "Ошибка: число должно быть в диапазоне от 10 до 1000000000!" << endl;
        system("pause");
        return 1;
    }

    // 3. Вывод цифр в обратном порядке
    cout << "Цифры числа в обратном порядке:" << endl;

    // Обработка случая, когда число равно 0 (хотя по условию это невозможно)
    if (number == 0) {
        cout << "0" << endl;
    }
    else {
        // Извлекаем цифры числа и выводим их в обратном порядке
        // "Пока число больше 0, продолжаем извлекать цифры"
        while (number > 0) {
            unsigned int digit = number % 10;  // Получаем последнюю цифру (остаток от деления на 10)
            cout << digit;                     // Выводим эту цифру
            number /= 10;                      // Удаляем последнюю цифру из числа (делим на 10)
        }
        cout << endl;
    }

    cout << endl;
    system("pause"); // Ожидаем нажатия клавиши перед закрытием окна
}