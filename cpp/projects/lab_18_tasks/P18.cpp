#pragma once                      // Защита от повторного включения файла
#include <iostream>               // Подключаем библиотеку для ввода/вывода
#include <cstdlib>                // Для rand() и srand()
#include <ctime>                  // Для time()
#include <cmath>                  // Для sqrt()

using std::cin;                   // Используем cin из пространства std
using std::cout;                  // Используем cout из пространства std
using std::endl;                  // Используем endl из пространства std

int main() {
    setlocale(LC_ALL, ".1251");   // Устанавливаем русскую кодировку
    srand(static_cast<unsigned int>(time(0)));  // Инициализируем генератор случайных чисел

    cout << "Задание:" << endl;
    cout << "Зона обстрела представляет собой квадрат со стороной a, левый нижний угол находится в начале координат." << endl;
    cout << "Снаряд поражает цель, если подрыв происходит на расстоянии не более, чем r метров от цели." << endl;
    cout << "Пользователь вводит с клавиатуры вещественные числа a, r и целое число N – количество целей (от 2 до 5)." << endl;
    cout << "Далее программа генерирует координаты цели, пользователь вводит координаты выстрела," << endl;
    cout << "программа сообщает 'промах' или 'цель поражена' и дает рекомендацию по корректировке огня." << endl;
    cout << "Процесс повторяется до поражения цели, затем переходит к следующей цели." << endl;
    cout << "В конце программа выводит расход снарядов по каждой цели и общий расход.\n" << endl;

    // 1. ВВОД ПАРАМЕТРОВ (с проверкой по условию)
    double a, r;  // a - сторона квадрата, r - радиус поражения
    int N;        // N - количество целей

    cout << "Введите параметры (по условию задачи):" << endl;
    cout << "Сторона квадрата a (100-500): ";
    cin >> a;
    cout << "Радиус поражения r (10-25): ";
    cin >> r;
    cout << "Количество целей N (2-5): ";
    cin >> N;

    // ПРОВЕРКА: все ли параметры соответствуют условию
    // Используем ИЛИ (||) для проверки каждого условия
    if (a < 100 || a > 500 || r < 10 || r > 25 || N < 2 || N > 5) {
        cout << "Ошибка! Параметры не соответствуют условию задачи!" << endl;
        cout << "Должно быть: a=100-500, r=10-25, N=2-5" << endl;
        system("pause");  // Ждем нажатия клавиши
        return 1;         // Завершаем программу с ошибкой
    }

    // 2. СОЗДАНИЕ ДИНАМИЧЕСКИХ МАССИВОВ
    // динамические массивы

    double* targetX = new double[N];  // Координаты X целей
    double* targetY = new double[N];  // Координаты Y целей
    bool* destroyed = new bool[N];    // Поражена ли цель? (true/false)
    int* shotsUsed = new int[N];      // Сколько снарядов потрачено на каждую цель

    // 3. ГЕНЕРАЦИЯ ЦЕЛЕЙ
    cout << "\nГенерация " << N << " целей..." << endl;

    for (int i = 0; i < N; i++) {
        // Генерируем случайные координаты в квадрате [0, a]
        // rand() дает число от 0 до RAND_MAX, преобразуем его в [0, a]
        targetX[i] = (rand() % (int)(a * 1000)) / 1000.0;
        targetY[i] = (rand() % (int)(a * 1000)) / 1000.0;

        destroyed[i] = false;  // Цель еще не поражена
        shotsUsed[i] = 0;      // Пока не потрачено снарядов

        // В реальной игре координаты не показываем!
        // Это было бы слишком просто :)
    }

    cout << "Цели размещены на поле. Начинаем стрельбу!\n" << endl;

    // 4. ОСНОВНОЙ ЦИКЛ СТРЕЛЬБЫ
    int totalShots = 0;        // Общий расход снарядов
    int targetsDestroyed = 0;  // Сколько целей поражено

    // Цикл продолжается, пока не поражены все цели
    while (targetsDestroyed < N) {
        // Находим первую непораженную цель
        int currentTarget = -1;  // Индекс текущей цели

        for (int i = 0; i < N; i++) {
            if (!destroyed[i]) {  // Если цель не поражена
                currentTarget = i;
                break;  // Нашли цель, выходим из цикла
            }
        }

        cout << "=== Цель " << (currentTarget + 1) << " ===" << endl;
        bool hit = false;  // Попали ли по текущей цели?

        // Стреляем по этой цели, пока не попадем
        while (!hit) {
            // Ввод координат выстрела
            double shotX, shotY;
            cout << "\nВведите координаты выстрела (x y): ";
            cin >> shotX >> shotY;

            // Увеличиваем счетчики
            shotsUsed[currentTarget]++;  // Для этой цели
            totalShots++;                // Общий счетчик

            // Вычисляем расстояние от выстрела до цели
            // Формула: расстояние = корень((x2-x1)2 + (y2-y1)2)
            double distanceX = targetX[currentTarget] - shotX;
            double distanceY = targetY[currentTarget] - shotY;
            double distance = sqrt(distanceX * distanceX + distanceY * distanceY);

            // Проверяем попадание
            if (distance <= r) {
                // ПОПАДАНИЕ!
                cout << ">>> Цель поражена! <<<" << endl;
                destroyed[currentTarget] = true;  // Отмечаем как пораженную
                targetsDestroyed++;               // Увеличиваем счетчик
                hit = true;                       // Выходим из цикла стрельбы
            }
            else {
                // ПРОМАХ
                cout << "Промах! Расстояние до цели: " << distance << endl;

                // РЕКОМЕНДАЦИЯ ПО КОРРЕКТИРОВКЕ
                cout << "Корректировка: ";

                // Проверяем горизонтальное направление
                if (shotX < targetX[currentTarget]) {
                    cout << "вправо";
                }
                else if (shotX > targetX[currentTarget]) {
                    cout << "влево";
                }

                // Проверяем вертикальное направление
                if (shotY < targetY[currentTarget]) {
                    if (shotX != targetX[currentTarget]) cout << ", ";
                    cout << "вверх";
                }
                else if (shotY > targetY[currentTarget]) {
                    if (shotX != targetX[currentTarget]) cout << ", ";
                    cout << "вниз";
                }

                cout << endl;
            }
        }

        cout << endl;  // Пустая строка для читаемости
    }

    // 5. ВЫВОД РЕЗУЛЬТАТОВ
    cout << "========================================" << endl;
    cout << "          РЕЗУЛЬТАТЫ СТРЕЛЬБЫ" << endl;
    cout << "========================================\n" << endl;

    cout << "Расход снарядов по целям:" << endl;
    for (int i = 0; i < N; i++) {
        cout << "Цель " << (i + 1) << ": " << shotsUsed[i] << " снарядов" << endl;
    }

    cout << "\nОбщий расход снарядов: " << totalShots << endl;

    // 6. ОСВОБОЖДЕНИЕ ПАМЯТИ
    // ВАЖНО: По условию задачи, если используем динамические массивы,
    // НЕОБХОДИМО очищать память с помощью delete[]
    // Иначе будет утечка памяти (грубая ошибка!)

    delete[] targetX;     // Освобождаем память массива X
    delete[] targetY;     // Освобождаем память массива Y
    delete[] destroyed;   // Освобождаем память массива состояний
    delete[] shotsUsed;   // Освобождаем память массива счетчиков

    system("pause");
}